from dataclasses import dataclass
from io import StringIO
from typing import Any, cast, overload

from llvmlite import binding
from xdsl.backend.llvm.convert import convert_module
from xdsl.context import Context
from xdsl.dialects import builtin, llvm
from xdsl.ir import Attribute, Block, Operation, SSAValue
from xdsl.printer import Printer
from xdsl.transforms.canonicalize import CanonicalizePass

from adaptix._internal.code_tools.cpython_layout.selection import require_cpython_layout
from adaptix._internal.code_tools.native_callable import (
    ExecutableMemory,
    MethodDef,
    NativeCode,
    NativeCodeData,
    NativeMethod,
)
from adaptix._internal.code_tools.x86_64_compiler import check_native_platform, inline_refcount_mode

PTR = llvm.LLVMPointerType()
PREDICATES = {"eq": 0, "ne": 1, "ult": 6, "uge": 9, "slt": 2}


@dataclass
class OwnedValue:
    storage: SSAValue


@dataclass
class LLVMArtifact:
    xdsl_ir: str
    llvm_ir: str
    optimized_ir: str
    assembly: str
    object_code: bytes
    text: bytes
    timings_ns: dict[str, int]
    engine: Any
    module: Any
    target: Any
    address: int
    raw_address: int


class LLVMMemory(ExecutableMemory):
    def __init__(self, artifact: LLVMArtifact):
        self.artifact = artifact
        self.address = artifact.address


class LLVMCode(NativeCode):
    __slots__ = ()

    def __new__(cls, name: str, artifact: LLVMArtifact, constants: list[Any], program=None):
        method_name = name.encode()
        documentation = f"{name}($self, /, data)\n--\n\nGenerated by xDSL and LLVM.".encode()
        method = NativeMethod(
            bytes(MethodDef(method_name, artifact.address, 0x0080 | 0x0002, documentation)),
            method_name,
            documentation,
        )
        return NativeCodeData.__new__(
            cls,
            artifact.text,
            artifact.assembly,
            tuple(constants),
            LLVMMemory(artifact),
            method,
            0,
            program,
            ("data",),
        )

    @property
    def raw_address(self) -> int:
        return cast(LLVMMemory, self.memory).artifact.raw_address


class XDSLCompiler:
    def __init__(self, name: str, *, opt_level: int = 2, canonicalize: bool = True, capture_artifacts: bool = False):
        check_native_platform()
        self.started = time.perf_counter_ns()
        self.layout = require_cpython_layout()
        self.refcount_mode = inline_refcount_mode()
        self.name = name
        self.opt_level = opt_level
        self.canonicalize = canonicalize
        self.capture_artifacts = capture_artifacts
        self.constants: list[Any] = []
        self.declarations: dict[str, llvm.FuncOp] = {}
        self.owned: list[OwnedValue] = []
        self.entry = Block(arg_types=[PTR])
        self.blocks = [self.entry]
        self.raw = llvm.FuncOp("adaptix_raw", llvm.LLVMFunctionType([PTR], PTR), linkage=llvm.LinkageAttr("external"))
        self.raw.body.add_block(self.entry)
        self.block = self.entry
        self.data = self.entry.args[0]
        self.one = self.integer(1)
        self.zero = self.integer(0)
        self.null = self.emit(llvm.IntToPtrOp(self.zero))
        self.body = self.new_block()
        self.add(llvm.BrOp(self.body))
        self.block = self.body
        self.fallback = self.new_block()
        self.error = self.new_block()

    def add(self, op: Operation) -> None:
        self.block.add_op(op)

    def emit(self, op: Operation) -> SSAValue:
        self.add(op)
        return op.results[0]

    def integer(self, value: int, tp=builtin.i64) -> SSAValue:
        return self.emit(llvm.ConstantOp(builtin.IntegerAttr(value, tp), tp))

    def pointer(self, value: Any) -> SSAValue:
        self.constants.append(value)
        return self.emit(llvm.IntToPtrOp(self.integer(id(value))))

    def address(self, value: int) -> SSAValue:
        return self.emit(llvm.IntToPtrOp(self.integer(value)))

    def cstring(self, value: str) -> SSAValue:
        data = value.encode() + b"\x00"
        self.constants.append(data)
        return self.address(cast(int, ctypes.cast(ctypes.c_char_p(data), ctypes.c_void_p).value))

    def new_block(self, *types) -> Block:
        block = Block(arg_types=types)
        self.raw.body.add_block(block)
        self.blocks.append(block)
        return block

    def guard(self, condition: SSAValue, failure: Block | None = None) -> None:
        passed = self.new_block()
        self.add(llvm.CondBrOp(condition, passed, [], failure or self.fallback, []))
        self.block = passed

    def compare(self, left: SSAValue, right: SSAValue, predicate: str = "eq") -> SSAValue:
        if left.type == PTR:
            left = self.emit(llvm.PtrToIntOp(left))
            right = self.emit(llvm.PtrToIntOp(right))
        return self.emit(llvm.ICmpOp(left, right, builtin.IntegerAttr(PREDICATES[predicate], builtin.i64)))

    def gep(self, pointer: SSAValue, offset: int | SSAValue, tp=builtin.i8) -> SSAValue:
        return self.emit(llvm.GEPOp.from_mixed_indices(pointer, [offset], tp))

    def load(self, pointer: SSAValue, offset: int = 0, tp=PTR) -> SSAValue:
        return self.emit(llvm.LoadOp(self.gep(pointer, offset), tp))

    def check_type(self, value: SSAValue, types: tuple[type, ...]) -> None:
        if not types:
            return
        cls = self.load(value, self.layout.object_type)
        checks = [self.compare(cls, self.pointer(expected)) for expected in types]
        condition = checks[0]
        for check in checks[1:]:
            condition = self.emit(llvm.OrOp(condition, check))
        self.guard(condition)

    @overload
    def call(self, name: str, *args: SSAValue, result: None) -> None: ...

    @overload
    def call(self, name: str, *args: SSAValue, result: Attribute = PTR) -> SSAValue: ...

    def call(self, name: str, *args: SSAValue, result: Attribute | None = PTR) -> SSAValue | None:
        if name not in self.declarations:
            address = ctypes.cast(getattr(ctypes.pythonapi, name), ctypes.c_void_p).value
            binding.add_symbol(name, address)
            self.declarations[name] = llvm.FuncOp(
                name,
                llvm.LLVMFunctionType([arg.type for arg in args], result),
                linkage=llvm.LinkageAttr("external"),
            )
        op = llvm.CallOp(name, *args, return_type=result)
        self.add(op)
        return op.results[0] if op.results else None

    def storage(self, tp=PTR, size: int = 1) -> SSAValue:
        # Place every ownership slot in the entry so all error paths see NULL.
        previous = self.block
        self.block = self.entry
        terminator = cast(Operation, self.entry.last_op)
        count = llvm.ConstantOp(builtin.IntegerAttr(size, builtin.i64), builtin.i64)
        self.entry.insert_op_before(count, terminator)
        allocation = llvm.AllocaOp(count.results[0], tp, alignment=8)
        self.entry.insert_op_before(allocation, terminator)
        if size == 1 and tp == PTR:
            self.entry.insert_op_before(llvm.StoreOp(self.null, allocation.results[0]), terminator)
        self.block = previous
        return allocation.results[0]

    def own(self, value: SSAValue) -> OwnedValue:
        owned = OwnedValue(self.storage())
        self.owned.append(owned)
        self.add(llvm.StoreOp(value, owned.storage))
        return owned

    def keep(self, value: SSAValue) -> OwnedValue:
        self.incref(value)
        return self.own(value)

    def incref(self, value: SSAValue) -> None:
        self.refcount(value, increment=True)

    def refcount(self, value: SSAValue, *, increment: bool) -> None:
        if self.refcount_mode is None:
            self.call("Py_IncRef" if increment else "Py_DecRef", value, result=None)
            return
        finished, active = self.new_block(), self.new_block()
        count_type = (
            builtin.i64
            if self.refcount_mode == "legacy" or (not increment and self.refcount_mode == "immortal64")
            else builtin.i32
        )
        if self.refcount_mode != "legacy":
            count = self.load(value, self.layout.object_refcount, builtin.i32)
            limit = 0xC0000000 if self.refcount_mode == "immortal32" else 0xFFFFFFFF
            check = (
                self.compare(count, self.integer(limit, builtin.i32), "ult")
                if increment
                else self.compare(count, self.integer(0, builtin.i32), "slt")
            )
            self.add(llvm.CondBrOp(check, active if increment else finished, [], finished if increment else active, []))
        else:
            self.add(llvm.BrOp(active))
        self.block = active
        count = self.load(value, self.layout.object_refcount, count_type)
        one = self.integer(1, count_type)
        changed = self.emit(llvm.AddOp(count, one) if increment else llvm.SubOp(count, one))
        self.add(llvm.StoreOp(changed, self.gep(value, self.layout.object_refcount)))
        if increment:
            self.add(llvm.BrOp(finished))
        else:
            destroy = self.new_block()
            self.add(llvm.CondBrOp(self.compare(changed, self.integer(0, count_type)), destroy, [], finished, []))
            self.block = destroy
            self.call("_Py_Dealloc", value, result=None)
            self.add(llvm.BrOp(finished))
        self.block = finished

    def release(self, owned: OwnedValue) -> None:
        value = self.emit(llvm.LoadOp(owned.storage, PTR))
        active, done = self.new_block(), self.new_block()
        self.add(llvm.CondBrOp(self.compare(value, self.null, "ne"), active, [], done, []))
        self.block = active
        self.add(llvm.StoreOp(self.null, owned.storage))
        self.refcount(value, increment=False)
        self.add(llvm.BrOp(done))
        self.block = done

    def cleanup(self, exclude: OwnedValue | None = None) -> None:
        for owned in reversed(self.owned):
            if owned is not exclude:
                self.release(owned)

    def checked(self, name: str, *args: SSAValue) -> OwnedValue:
        value = self.call(name, *args)
        owned = self.own(value)
        self.guard(self.compare(value, self.null, "ne"), self.error)
        return owned

    def value(self, owned: OwnedValue) -> SSAValue:
        return self.emit(llvm.LoadOp(owned.storage, PTR))

    def finish(self, result: OwnedValue, fallback, *, program=None) -> LLVMCode:
        value = self.value(result)
        self.cleanup(exclude=result)
        self.add(llvm.ReturnOp(value))
        self.block = self.fallback
        self.cleanup()
        value = self.call("PyObject_CallOneArg", self.pointer(fallback), self.data)
        self.add(llvm.ReturnOp(value))
        self.block = self.error
        exception = [self.storage() for index in range(3)]
        self.call("PyErr_Fetch", *exception, result=None)
        self.cleanup()
        self.call("PyErr_Restore", *(self.emit(llvm.LoadOp(slot, PTR)) for slot in exception), result=None)
        self.add(llvm.ReturnOp(self.null))
        public = self.public_entry()
        module = builtin.ModuleOp([*self.declarations.values(), self.raw, public])
        return LLVMCode(self.name, self.compile_module(module), self.constants, program)

    def compile_module(self, module: builtin.ModuleOp) -> LLVMArtifact:
        module.verify()
        built = time.perf_counter_ns()
        context = Context()
        context.load_dialect(builtin.Builtin)
        context.load_dialect(llvm.LLVM)
        if self.canonicalize:
            CanonicalizePass().apply(context, module)
        module.verify()
        binding.initialize_native_target()
        binding.initialize_native_asmprinter()
        target = binding.Target.from_default_triple().create_target_machine(
            cpu=binding.get_host_cpu_name(),
            features=binding.get_host_cpu_features().flatten(),
            opt=self.opt_level,
            jit=True,
        )
        llvm_module = convert_module(module, fallback_target_triple=target.triple, data_layout=str(target.target_data))
        translated = time.perf_counter_ns()
        native = binding.parse_assembly(str(llvm_module))
        native.verify()
        options = binding.PipelineTuningOptions(speed_level=self.opt_level)
        options.slp_vectorization = True
        with options, binding.create_pass_builder(target, options) as passes, passes.getModulePassManager() as manager:
            manager.run(native, passes)
        optimized = time.perf_counter_ns()
        engine = binding.create_mcjit_compiler(native, target)
        engine.finalize_object()
        done = time.perf_counter_ns()
        xdsl_ir = optimized_ir = assembly = ""
        obj = text = b""
        if self.capture_artifacts:
            stream = StringIO()
            Printer(stream=stream).print_op(module)
            xdsl_ir = stream.getvalue()
            optimized_ir = str(native)
            assembly = target.emit_assembly(native)
            obj = target.emit_object(native)
            object_ref = binding.ObjectFileRef.from_data(obj)
            text = b"".join(section.data() for section in object_ref.sections() if section.is_text())
        diagnosed = time.perf_counter_ns()
        return LLVMArtifact(
            xdsl_ir,
            str(llvm_module),
            optimized_ir,
            assembly,
            obj,
            text,
            {
                "build": built - self.started,
                "translate": translated - built,
                "optimize": optimized - translated,
                "jit": done - optimized,
                "diagnostics": diagnosed - done,
            },
            engine,
            native,
            target,
            engine.get_function_address("adaptix_entry"),
            engine.get_function_address("adaptix_raw"),
        )

    def public_entry(self) -> llvm.FuncOp:
        # Emit the ordinary unary METH_FASTCALL | METH_KEYWORDS entry, keeping GIL.
        raw_blocks = self.raw
        entry = llvm.FuncOp(
            "adaptix_entry",
            llvm.LLVMFunctionType([PTR, PTR, builtin.i64, PTR], PTR),
            linkage=llvm.LinkageAttr("external"),
        )
        self.raw = entry
        first = Block(arg_types=[PTR, PTR, builtin.i64, PTR])
        entry.body.add_block(first)
        self.block = first
        args, nargs, keywords = first.args[1:]
        null = self.emit(llvm.IntToPtrOp(self.integer(0)))
        simple, keyword, invalid, ready = (self.new_block() for index in range(4))
        self.add(llvm.CondBrOp(self.compare(keywords, null), simple, [], keyword, []))
        self.block = simple
        self.add(llvm.CondBrOp(self.compare(nargs, self.integer(1)), ready, [], invalid, []))
        self.block = keyword
        count = self.call("PyTuple_Size", keywords, result=builtin.i64)
        nonempty = self.new_block()
        self.add(llvm.CondBrOp(self.compare(count, self.integer(0)), simple, [], nonempty, []))
        self.block = nonempty
        valid = self.emit(llvm.AndOp(self.compare(count, self.integer(1)), self.compare(nargs, self.integer(0))))
        named = self.new_block()
        self.add(llvm.CondBrOp(valid, named, [], invalid, []))
        self.block = named
        key = self.call("PyTuple_GetItem", keywords, self.integer(0))
        equal = self.call("PyUnicode_CompareWithASCIIString", key, self.cstring("data"), result=builtin.i32)
        self.add(llvm.CondBrOp(self.compare(equal, self.integer(0, builtin.i32)), ready, [], invalid, []))
        self.block = ready
        data = self.emit(llvm.LoadOp(args, PTR))
        result = self.emit(llvm.CallOp("adaptix_raw", data, return_type=PTR))
        self.add(llvm.ReturnOp(result))
        self.block = invalid
        self.call(
            "PyErr_SetString",
            self.pointer(TypeError),
            self.cstring(f"{self.name}() takes one argument named 'data'"),
            result=None,
        )
        self.add(llvm.ReturnOp(null))
        self.raw = raw_blocks
        return entry
